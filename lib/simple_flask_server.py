def process_job(job_id):
    """Simulate background job processing with progress updates."""
    job = jobs.get(job_id)
    if not job:
        return
    progress = 0.0
    while progress < 1.0:
        time.sleep(1)
        progress += 0.1
        if progress > 1.0:
            progress = 1.0
        job["progress"] = progress
        if progress >= 1.0:
            job["status"] = "completed"
            job["transcript"] = generate_mock_transcript()
            job["segments"] = generate_mock_segments()


def download_session_files(session_id, token):
    """
    Download all files from a session using requests.
    This is more reliable than curl for this purpose.
    """
    session_dir = os.path.join(SESSION_FOLDER, session_id)
    os.makedirs(session_dir, exist_ok=True)

    # Headers for authentication
    headers = {
        "X-Forward-Auth": token,
        "Authorization": f"Bearer {token}",
        "User-Agent": "Mozilla/5.0 (compatible; LT-Uploader/1.0)",
    }
    cookies = {"_forward_auth": token}

    # First, get the main HTML page to see what's available
    base_url = f"{INTERNAL_SERVER_URL}/archivesession/{session_id}"
    
    try:
        # Download the main HTML page
        resp = requests.get(
            base_url,
            headers=headers,
            cookies=cookies,
            verify=False,
            allow_redirects=True,
            timeout=30,
        )
        
        if resp.status_code == 200:
            html_path = os.path.join(session_dir, "index.html")
            with open(html_path, "w", encoding="utf-8") as f:
                f.write(resp.text)
            logging.info(f"Downloaded index.html for session {session_id}")
            
            # Parse HTML to find media files
            html_content = resp.text
            
            # Look for video source
            video_match = re.search(r'<source src="([^"]+)"', html_content)
            if video_match:
                video_url = video_match.group(1)
                if video_url.startswith("/"):
                    video_url = f"{INTERNAL_SERVER_URL}{video_url}"
                try:
                    video_resp = requests.get(
                        video_url,
                        headers=headers,
                        cookies=cookies,
                        verify=False,
                        timeout=60,
                    )
                    if video_resp.status_code == 200:
                        video_path = os.path.join(session_dir, "video.mp4")
                        with open(video_path, "wb") as f:
                            f.write(video_resp.content)
                        logging.info(f"Downloaded video for session {session_id}")
                except Exception as e:
                    logging.warning(f"Could not download video: {e}")
            
            # Look for subtitle tracks
            track_matches = re.findall(r'<track label="([^"]+)" kind="subtitles" src="([^"]+)"', html_content)
            for label, src in track_matches:
                if src.startswith("/"):
                    src = f"{INTERNAL_SERVER_URL}{src}"
                try:
                    track_resp = requests.get(
                        src,
                        headers=headers,
                        cookies=cookies,
                        verify=False,
                        timeout=30,
                    )
                    if track_resp.status_code == 200:
                        track_path = os.path.join(session_dir, f"subtitles_{label}.vtt")
                        with open(track_path, "wb") as f:
                            f.write(track_resp.content)
                        logging.info(f"Downloaded subtitles {label} for session {session_id}")
                except Exception as e:
                    logging.warning(f"Could not download subtitles {label}: {e}")
            
            # Look for audio sources
            audio_match = re.search(r'<source src="([^"]+)"[^>]*type="audio/', html_content)
            if audio_match:
                audio_url = audio_match.group(1)
                if audio_url.startswith("/"):
                    audio_url = f"{INTERNAL_SERVER_URL}{audio_url}"
                try:
                    audio_resp = requests.get(
                        audio_url,
                        headers=headers,
                        cookies=cookies,
                        verify=False,
                        timeout=60,
                    )
                    if audio_resp.status_code == 200:
                        audio_path = os.path.join(session_dir, "audio.wav")
                        with open(audio_path, "wb") as f:
                            f.write(audio_resp.content)
                        logging.info(f"Downloaded audio for session {session_id}")
                except Exception as e:
                    logging.warning(f"Could not download audio: {e}")
        
        # Also try to download common media files directly
        media_extensions = [".mp4", ".webm", ".wav", ".mp3", ".vtt", ".srt"]
        for ext in media_extensions:
            media_url = f"{base_url}/media{ext}"
            try:
                media_resp = requests.get(
                    media_url,
                    headers=headers,
                    cookies=cookies,
                    verify=False,
                    timeout=30,
                )
                if media_resp.status_code == 200:
                    filename = f"media{ext}"
                    if ext == ".mp4":
                        filename = "video.mp4"
                    elif ext == ".wav" or ext == ".mp3":
                        filename = f"audio{ext}"
                    elif ext == ".vtt" or ext == ".srt":
                        filename = f"subtitles{ext}"
                    file_path = os.path.join(session_dir, filename)
                    with open(file_path, "wb") as f:
                        f.write(media_resp.content)
                    logging.info(f"Downloaded {filename} for session {session_id}")
            except Exception as e:
                pass  # Silently skip if file doesn't exist
        
        # Check if we have any files
        files = os.listdir(session_dir)
        if files:
            logging.info(f"Session {session_id}: Downloaded {len(files)} files")
            return True
        else:
            logging.warning(f"Session {session_id}: No files downloaded")
            return False
            
    except Exception as e:
        logging.error(f"Error downloading session {session_id}: {e}")
        return False


