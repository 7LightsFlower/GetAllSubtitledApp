@app.route("/session_output/<session_id>", methods=["GET"])
def get_session_output(session_id):
    """Get the session output as a JSON response with file URLs."""
    session_dir = os.path.join(SESSION_FOLDER, session_id)

    # Get token from request
    token = request.headers.get("Authorization", "").replace("Bearer ", "")
    if not token:
        token = request.cookies.get("_forward_auth", "")

    # Check if we have cached files
    files = []
    download_success = False
    
    if os.path.exists(session_dir):
        # List existing files
        for file in os.listdir(session_dir):
            file_path = os.path.join(session_dir, file)
            if os.path.isfile(file_path) and os.path.getsize(file_path) > 0:
                files.append(
                    {
                        "name": file,
                        "size": os.path.getsize(file_path),
                        "url": f"/session_file/{session_id}/{file}",
                    }
                )
        
        # If we have files, return them
        if files:
            return (
                jsonify(
                    {
                        "session_id": session_id,
                        "files": files,
                        "total_files": len(files),
                        "session_url": f"{INTERNAL_SERVER_URL}/archivesession/{session_id}",
                        "status": "ready",
                        "cached": True,
                    }
                ),
                200,
            )
    
    # If no cached files or they're empty, try to download
    if token:
        logging.info(f"Downloading session {session_id} from internal server")
        download_success = download_session_files(session_id, token)
        
        # Check again for downloaded files
        if os.path.exists(session_dir):
            for file in os.listdir(session_dir):
                file_path = os.path.join(session_dir, file)
                if os.path.isfile(file_path) and os.path.getsize(file_path) > 0:
                    files.append(
                        {
                            "name": file,
                            "size": os.path.getsize(file_path),
                            "url": f"/session_file/{session_id}/{file}",
                        }
                    )
    
    # Return whatever we found
    status = "ready" if files else "processing"
    return (
        jsonify(
            {
                "session_id": session_id,
                "files": files,
                "total_files": len(files),
                "session_url": f"{INTERNAL_SERVER_URL}/archivesession/{session_id}",
                "status": status,
                "cached": download_success,
            }
        ),
        200,
    )


